// Словарь событий и фильтрация набора событий снапшота.
//
// События — это строки, которые ядро и подсчёт очков складывают в events_ и
// отдают в снапшоте. Снапшот содержит события ТОЛЬКО последнего действия
// (Game::apply очищает набор на любом действии, кроме Tick), поэтому фильтр
// работает как «показать из последнего набора только запрошенное».
#pragma once

#include <optional>
#include <set>
#include <string>
#include <string_view>
#include <vector>

namespace tetris {

// Множество имён событий, запрошенных потребителем.
using EventFilter = std::set<std::string>;

// Все имена событий, которые система может породить: управление из ядра и
// события фиксации/линий из подсчёта очков. Единый источник для проверки
// пользовательского списка, текста ошибки и справки CLI.
const std::vector<std::string>& known_events();

// Разбор списка имён через запятую. Пробелы по краям списка и вокруг запятых
// не считаются частью имени; регистр значим.
//
// Возвращает std::nullopt, если список пуст, содержит пустое имя или имя вне
// known_events(); в этом случае в error кладётся готовое для CLI сообщение
// (с перечнем допустимых имён). Ошибка — сознательное решение: успешный прогон
// с опечаткой в фильтре выглядел бы как «событий не было».
std::optional<EventFilter> parse_event_filter(std::string_view spec, std::string& error);

// Отбор событий, входящих в фильтр. Порядок результата — порядок исходного
// набора (не порядок списка пользователя), дубликаты в наборе не появляются.
std::vector<std::string> filter_events(const std::vector<std::string>& events,
                                       const EventFilter& filter);

// Текст перечня допустимых имён одной строкой: "left, right, ...".
// Используется в сообщении об ошибке и в справке CLI.
std::string known_events_list();

}  // namespace tetris
